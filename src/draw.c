/* Match the vendor's portrait rotation without a transform buffer. */
static void px_set(uint8_t *pixels, int x, int y, bool on) {
    int nx;
    int ny;
    size_t index;
    uint8_t mask;

    if (x < 0 || x >= SPACETIME_WIDTH || y < 0 || y >= SPACETIME_HEIGHT) {
        return;
    }

#ifdef CONFIG_SHARP_MIP_ROTATE_180
    nx = y;
    ny = (SPACETIME_WIDTH - 1) - x;
#else
    nx = (SPACETIME_HEIGHT - 1) - y;
    ny = x;
#endif
    index = (size_t)ny * (SPACETIME_NATIVE_WIDTH / 8) + (size_t)nx / 8;
    mask = (uint8_t)(0x80u >> (nx & 7));

    if (on) {
        pixels[index] |= mask;
    } else {
        pixels[index] &= (uint8_t)~mask;
    }
}

static void fill_rect(uint8_t *pixels, int x, int y, int w, int h, bool on) {
    int i;
    int j;

    for (j = 0; j < h; j++) {
        for (i = 0; i < w; i++) {
            px_set(pixels, x + i, y + j, on);
        }
    }
}

/* C division truncates toward zero; line rounding needs floor for negative slopes. */
static int floor_div(int a, int b) {
    int q = a / b;

    if (a % b != 0 && a < 0) {
        q--;
    }
    return q;
}

static void draw_line(uint8_t *pixels, int x0, int y0, int x1, int y1, bool on) {
    const int dx = x1 - x0;
    const int dy = y1 - y0;
    const int ax = dx < 0 ? -dx : dx;
    const int ay = dy < 0 ? -dy : dy;
    const int steps = ax > ay ? ax : ay;
    int i;

    if (steps == 0) {
        px_set(pixels, x0, y0, on);
        return;
    }
    for (i = 0; i <= steps; i++) {
        const int px = x0 + floor_div(2 * dx * i + steps, 2 * steps);
        const int py = y0 + floor_div(2 * dy * i + steps, 2 * steps);

        px_set(pixels, px, py, on);
    }
}

static void fill_circle(uint8_t *pixels, int cx, int cy, int r, bool on) {
    int dy;

    for (dy = -r; dy <= r; dy++) {
        int n = r * r - dy * dy;
        int dx = 0;

        while ((dx + 1) * (dx + 1) <= n) {
            dx++;
        }
        fill_rect(pixels, cx - dx, cy + dy, 2 * dx + 1, 1, on);
    }
}

/* 5-bit rows, MSB = leftmost of the 5 columns; 6 px advance, 7 px tall. */
static const uint8_t FONT[][7] = {
    /* ' ' */ {0, 0, 0, 0, 0, 0, 0},
    /* '0' */ {14, 17, 19, 21, 25, 17, 14},
    /* '1' */ {4, 12, 4, 4, 4, 4, 14},
    /* '2' */ {14, 17, 1, 2, 4, 8, 31},
    /* '3' */ {30, 1, 1, 14, 1, 1, 30},
    /* '4' */ {2, 6, 10, 18, 31, 2, 2},
    /* '5' */ {31, 16, 16, 30, 1, 1, 30},
    /* '6' */ {14, 16, 16, 30, 17, 17, 14},
    /* '7' */ {31, 1, 2, 4, 8, 8, 8},
    /* '8' */ {14, 17, 17, 14, 17, 17, 14},
    /* '9' */ {14, 17, 17, 15, 1, 1, 14},
    /* 'M' */ {17, 27, 21, 21, 17, 17, 17},
    /* 'P' */ {30, 17, 17, 30, 16, 16, 16},
    /* 'W' */ {17, 17, 17, 21, 21, 21, 10},
};

static int font_index(char c) {
    if (c >= '0' && c <= '9') {
        return 1 + (c - '0');
    }
    switch (c) {
    case 'M':
        return 11;
    case 'P':
        return 12;
    case 'W':
        return 13;
    default:
        return 0;
    }
}

static void draw_text(uint8_t *pixels, const char *s, int x, int y, bool on) {
    int i;

    for (i = 0; s[i] != '\0'; i++) {
        const uint8_t *rows = FONT[font_index(s[i])];
        int j;
        int k;

        for (j = 0; j < 7; j++) {
            for (k = 0; k < 5; k++) {
                if ((rows[j] & (uint8_t)(16 >> k)) != 0) {
                    px_set(pixels, x + i * 6 + k, y + j, on);
                }
            }
        }
    }
}

