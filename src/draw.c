void spacetime_draw_art(uint8_t *pixels) {
    int row;
    int x;

    if (pixels == NULL) {
        return;
    }
    for (row = 0; row < SPACETIME_ART_HEIGHT; row++) {
        const uint8_t *src = &spacetime_art[row * SPACETIME_ART_STRIDE];

        for (x = 0; x < SPACETIME_ART_WIDTH; x++) {
            px_set(pixels, x, SPACETIME_ART_Y + row,
                  (src[x >> 3] & (uint8_t)(0x80u >> (x & 7))) != 0);
        }
    }
}

void spacetime_draw_battery(uint8_t *pixels, uint8_t level) {
    int fill;

    if (pixels == NULL) {
        return;
    }
    fill = level > 100 ? 100 : level;
    fill = (fill * 16 + 50) / 100; /* round(level * 16 / 100), 0..16 */

    fill_rect(pixels, 0, 0, 30, 19, false); /* clear x0..29, y0..18 */
    fill_rect(pixels, 3, 4, 18, 8, true);   /* body */
    fill_rect(pixels, 4, 5, 16, 6, false);  /* hollow interior */
    if (fill > 0) {
        fill_rect(pixels, 5, 6, fill, 4, true);
    }
    fill_rect(pixels, 21, 6, 2, 4, true);   /* terminal */
}

void spacetime_draw_output(uint8_t *pixels, enum spacetime_output output) {
    if (pixels == NULL) {
        return;
    }
    fill_rect(pixels, 50, 0, 18, 19, false); /* clear x50..67, y0..18 */

    switch (output) {
    case SPACETIME_BLE_CONNECTED:
        fill_rect(pixels, 52, 4, 13, 1, true);
        fill_rect(pixels, 53, 3, 11, 1, true);
        fill_rect(pixels, 55, 2, 7, 1, true);
        fill_rect(pixels, 54, 7, 9, 1, true);
        fill_rect(pixels, 55, 6, 7, 1, true);
        fill_rect(pixels, 56, 10, 5, 1, true);
        fill_rect(pixels, 57, 9, 3, 1, true);
        fill_rect(pixels, 58, 13, 1, 1, true);
        break;
    case SPACETIME_BLE_DISCONNECTED:
        draw_line(pixels, 55, 4, 63, 12, true);
        draw_line(pixels, 63, 4, 55, 12, true);
        break;
    case SPACETIME_USB:
        draw_line(pixels, 59, 13, 59, 2, true);
        draw_line(pixels, 57, 4, 59, 2, true);
        draw_line(pixels, 61, 4, 59, 2, true);
        draw_line(pixels, 59, 10, 55, 7, true);
        draw_line(pixels, 55, 7, 55, 5, true);
        fill_rect(pixels, 54, 3, 3, 3, true);
        draw_line(pixels, 59, 8, 63, 6, true);
        fill_rect(pixels, 62, 3, 3, 3, true);
        fill_rect(pixels, 58, 12, 3, 3, true);
        break;
    case SPACETIME_BLE_OPEN:
        fill_circle(pixels, 58, 7, 4, true);    /* ring */
        fill_rect(pixels, 57, 1, 3, 2, true);    /* tooth N */
        fill_rect(pixels, 57, 12, 3, 2, true);   /* tooth S */
        fill_rect(pixels, 52, 6, 2, 3, true);   /* tooth W */
        fill_rect(pixels, 63, 6, 2, 3, true);   /* tooth E */
        fill_rect(pixels, 54, 3, 2, 2, true);   /* tooth NW */
        fill_rect(pixels, 61, 3, 2, 2, true);   /* tooth NE */
        fill_rect(pixels, 54, 8, 2, 2, true);   /* tooth SW */
        fill_rect(pixels, 61, 8, 2, 2, true);   /* tooth SE */
        fill_circle(pixels, 58, 7, 2, false);   /* hub */
        break;
    }
}

void spacetime_draw_footer(uint8_t *pixels, uint8_t profile,
                           const uint8_t history[SPACETIME_WPM_SAMPLES]) {
    char label[8]; /* "WPM 255" worst case */
    int latest;
    int n = 4;
    int i;

    if (pixels == NULL || history == NULL) {
        return;
    }

    fill_rect(pixels, 0, SPACETIME_HEIGHT - 55, SPACETIME_WIDTH, 55, false);

    /* Profile badge: filled circle, number punched in black. */
    if (profile < 1) {
        profile = 1;
    } else if (profile > 5) {
        profile = 5;
    }
    fill_circle(pixels, 9, 112, 6, true);
    label[0] = (char)('0' + profile);
    label[1] = '\0';
    draw_text(pixels, label, 7, 109, false);

    /* Right-aligned "WPM n" label, exclusive right edge x65. */
    latest = history[SPACETIME_WPM_SAMPLES - 1];
    label[0] = 'W';
    label[1] = 'P';
    label[2] = 'M';
    label[3] = ' ';
    if (latest >= 100) {
        label[n++] = (char)('0' + latest / 100);
    }
    if (latest >= 10) {
        label[n++] = (char)('0' + (latest / 10) % 10);
    }
    label[n++] = (char)('0' + latest % 10);
    label[n] = '\0';
    draw_text(pixels, label, 65 - (n * 6 - 1), 109, true);

    /* Dotted grid rows y125 and y140, then the solid baseline y154. */
    for (i = 0; i < 2; i++) {
        int xx;

        for (xx = 3; xx < 65; xx += 4) {
            px_set(pixels, xx, 125 + i * 15, true);
        }
    }
    fill_rect(pixels, 3, 154, 62, 1, true);

    /* Polyline through the 14 samples, matching the reference curve(). */
    {
        int prev_x = 0;
        int prev_y = 0;

        for (i = 0; i < SPACETIME_WPM_SAMPLES; i++) {
            /* Keep the chart's scale fixed; the counter still shows actual WPM. */
            const int value = history[i] > SPACETIME_CHART_MAX_WPM ? SPACETIME_CHART_MAX_WPM
                                                                 : history[i];
            const int px = 4 + floor_div(118 * i + 13, 26);
            const int py = 153 - floor_div(54 * value + SPACETIME_CHART_MAX_WPM,
                                          2 * SPACETIME_CHART_MAX_WPM);

            if (i > 0) {
                draw_line(pixels, prev_x, prev_y, px, py, true);
            } else {
                px_set(pixels, px, py, true);
            }
            prev_x = px;
            prev_y = py;
        }
    }
}
